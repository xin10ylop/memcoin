@dataclass
class WalletScore:
    """Track record of one wallet across many tokens."""

    wallet: str
    n_tokens: int
    n_wins: int
    win_rate: float
    mean_forward_return: float
    confidence_low: float      # lower bound of the win-rate interval
    score: float               # 0..1, shrunk toward the base rate
    verdict: str

    @property
    def is_smart(self) -> bool:
        return self.verdict == "smart"


def score_wallets(
    entries: dict[str, list[tuple[str, float]]],
    *,
    base_rate: float,
    min_tokens: int = 8,
    z: float = 1.96,
) -> list[WalletScore]:
    """Rank wallets by forward performance of the tokens they bought.

    ``entries`` maps wallet → list of (token, forward_return) for each first
    entry that wallet made.

    Two corrections keep this honest. **Shrinkage**: a wallet with 3 wins from 3
    tokens is not better than one with 60 wins from 100; the estimate is pulled
    toward the population base rate in proportion to how little evidence there
    is. **Interval, not point estimate**: the Wilson lower bound is reported, so
    a wallet only ranks highly when its record is both good *and* long enough to
    believe.
    """
    scores: list[WalletScore] = []
    for wallet, records in entries.items():
        n = len(records)
        if n < min_tokens:
            continue
        rets = [r for _, r in records]
        wins = sum(1 for r in rets if r > 0)
        raw_rate = wins / n

        # Wilson score interval lower bound — well-behaved for small samples.
        denom = 1.0 + z * z / n
        centre = (raw_rate + z * z / (2 * n)) / denom
        margin = (z * math.sqrt(raw_rate * (1 - raw_rate) / n + z * z / (4 * n * n))) / denom
        lower = max(0.0, centre - margin)

        # Empirical-Bayes style shrinkage toward the base rate.
        prior_weight = float(min_tokens)
        shrunk = (wins + base_rate * prior_weight) / (n + prior_weight)

        if lower > base_rate * 1.25 and n >= min_tokens * 2:
            verdict = "smart"
        elif lower > base_rate:
            verdict = "promising"
        elif raw_rate < base_rate * 0.5:
            verdict = "avoid"
        else:
            verdict = "neutral"

        scores.append(
            WalletScore(
                wallet=wallet, n_tokens=n, n_wins=wins, win_rate=round(raw_rate, 4),
                mean_forward_return=round(statistics.fmean(rets), 4),
                confidence_low=round(lower, 4), score=round(shrunk, 4), verdict=verdict,
            )
        )
    # Rank by the shrunk score rather than the raw Wilson bound. Wilson is
    # correct for a single wallet in isolation, but we are selecting from
    # thousands: with that many candidates, some will post a short perfect
    # record by chance alone, and Wilson rates 8-from-8 above 45-from-60.
    # Shrinkage toward the base rate penalises exactly that, so it is the
    # appropriate key when the dominant risk is selection bias.
    scores.sort(key=lambda s: (s.score, s.n_tokens), reverse=True)
    return scores


def early_buyer_quality(
    trades: Sequence[Any], smart_wallets: set[str], first_n: int = 50
) -> dict[str, float]:
    """Share of a token's earliest buyers that are known-good wallets."""
    buys = sorted([t for t in trades if str(_get(t, "kind", "")) == "buy"], key=_ts)[:first_n]
    if not buys:
        return {"early_smart_share": 0.0, "early_smart_count": 0.0, "n_early_buyers": 0.0}
    wallets = {_get(t, "wallet", "") for t in buys}
    wallets.discard("")
    hits = wallets & smart_wallets
    return {
        "early_smart_share": len(hits) / max(len(wallets), 1),
        "early_smart_count": float(len(hits)),
        "n_early_buyers": float(len(wallets)),
    }


def _get(t: Any, key: str, default: Any = None) -> Any:
    if hasattr(t, "keys"):
        try:
            return t[key]
        except (KeyError, IndexError):
            return default
    return getattr(t, key, default)


def _ts(t: Any) -> int:
    value = _get(t, "ts", None)
    if value is None:
        value = _get(t, "timestamp", 0)
    if isinstance(value, str):
        try:
            return int(datetime.fromisoformat(value.replace("Z", "+00:00")).timestamp())
        except ValueError:
            return 0
    if isinstance(value, datetime):
        return int(value.timestamp())
    return int(value or 0)
